export const listeningSentences = sentenceRows.map(([verb, sentence, meaning, form, nearMiss]) => ({
    verb,
    sentence,
    meaning,
    form,
    nearMiss,
}));

const sentencesByVerb = new Map(listeningSentences.map(sentence => [sentence.verb, sentence]));

export const getListeningQuestion = verb => ({ ...verb, ...sentencesByVerb.get(verb.fr) });

export const getListeningOptions = ({ question, questionIndex }) => {
    const alternatives = listeningSentences
        .filter(
            candidate =>
                candidate.meaning !== question.meaning && candidate.meaning !== question.nearMiss,
        )
        .sort((first, second) => first.verb.localeCompare(second.verb));
    const offset = (questionIndex * 7) % alternatives.length;
    const choices = [
        { id: -1, text: question.nearMiss },
        ...[0, 1].map(index => ({
            id: -2 - index,
            text: alternatives[(offset + index) % alternatives.length].meaning,
        })),
    ];
    choices.splice(questionIndex % 4, 0, { id: question.id, text: question.meaning });

    return choices;
};
